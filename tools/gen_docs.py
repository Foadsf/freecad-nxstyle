"""Generate the reference parts of the documentation from the code, so they cannot drift.

    python tools/gen_docs.py
    python tools/gen_docs.py --results OUTDIR/tutorial.json   # take a replay's results first

Writes AsciiDoc partials to docs/modules/ROOT/partials/generated/ (not committed; the docs
workflow runs this before Antora):

- shortcuts.adoc       the NX key bindings (NXStyle/nxstyle/shortcuts.py, TABLE)
- settings.adoc        the nxstyle.json settings and defaults (NXStyle/nxstyle/config.py, DEFAULTS)
- ribbon-<app>.adoc    each application's ribbon: NX label -> FreeCAD command (resources/ribbons)
- tutorial-<X>.adoc    the replay steps of tutorial X (docs/results/tutorials.json, from a run)
- tutorial-summary.adoc the outcome counts of every tutorial

Only the standard library is used and nothing imports FreeCAD: the Python sources are read
with ast, so this runs in CI.
"""

import ast
import collections
import io
import json
import os
import sys
import tokenize

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PKG = os.path.join(ROOT, "NXStyle", "nxstyle")
OUT = os.path.join(ROOT, "docs", "modules", "ROOT", "partials", "generated")
RESULTS = os.path.join(ROOT, "docs", "results", "tutorials.json")


def esc(text):
    """Table-cell safe AsciiDoc text."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def kbd(keys):
    return "kbd:[" + keys.replace("]", "\\]") + "]" if keys else ""


def write(name, text):
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, name)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)
    return path


# ------------------------------------------------------------------------------------ shortcuts
def shortcut_entries():
    """Entry(...) calls of shortcuts.TABLE, with the section comments between them."""
    path = os.path.join(PKG, "shortcuts.py")
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src)
    table = next(n for n in tree.body if isinstance(n, ast.Assign)
                 and any(getattr(t, "id", "") == "TABLE" for t in n.targets))
    sections = {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT and tok.string.startswith("# ----"):
            sections[tok.start[0]] = tok.string.strip("# -").strip()
    fields = ["nx", "keys", "cmd", "context"]
    rows, current = [], "General"
    for call in table.value.elts:
        for line in sorted(sections):
            if line < call.lineno:
                current = sections[line]
        args = {fields[i]: ast.literal_eval(a) for i, a in enumerate(call.args)}
        args.update({k.arg: ast.literal_eval(k.value) for k in call.keywords})
        args["section"] = current
        rows.append(args)
    return rows


def gen_shortcuts():
    rows = shortcut_entries()
    out = ["// Generated by tools/gen_docs.py from NXStyle/nxstyle/shortcuts.py. Do not edit.", ""]
    by_section = collections.OrderedDict()
    for r in rows:
        by_section.setdefault(r["section"], []).append(r)
    for section, items in by_section.items():
        out += [f"== {section}", "", '[cols="3,2,2,4",options="header"]', "|===",
                "| NX command | Keys | Works in | FreeCAD command / note", ""]
        for r in items:
            cmd = r.get("cmd")
            cmd = cmd[0] if isinstance(cmd, list) else cmd
            where = "sketch edit" if r.get("context") == "sketch" else "anywhere"
            if r.get("message"):
                what = "_no FreeCAD equivalent:_ " + esc(r["message"])
            else:
                what = f"`{cmd}`" + (f" -- {esc(r['note'])}" if r.get("note") else "")
                if r.get("alias"):
                    what += " (FreeCAD's own key keeps working too)"
            out += [f"| {esc(r['nx'])}", f"| {kbd(r['keys'])}", f"| {where}", f"| {what}", ""]
        out += ["|===", ""]
    return write("shortcuts.adoc", "\n".join(out)), len(rows)


# ------------------------------------------------------------------------------------- settings
def gen_settings():
    path = os.path.join(PKG, "config.py")
    src = open(path, encoding="utf-8").read()
    tree = ast.parse(src)
    node = next(n for n in tree.body if isinstance(n, ast.Assign)
                and any(getattr(t, "id", "") == "DEFAULTS" for t in n.targets))
    lines = src.splitlines()
    comments = {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT:
            comments.setdefault(tok.start[0], []).append(tok.string.lstrip("# ").strip())
    out = ["// Generated by tools/gen_docs.py from NXStyle/nxstyle/config.py (DEFAULTS). Do not edit.", "",
           '[cols="2,2,5",options="header"]', "|===", "| Setting | Default | What it does", ""]
    keys = node.value.keys
    for i, k in enumerate(keys):
        name = ast.literal_eval(k)
        value = ast.literal_eval(node.value.values[i])
        first, last = k.lineno, node.value.values[i].end_lineno
        # comments on the lines of this entry, plus full-line comments right above it
        text = [c for ln in range(first, last + 1) for c in comments.get(ln, [])]
        ln = first - 1
        above = []
        while ln > 0 and lines[ln - 1].strip().startswith("#"):
            above.insert(0, lines[ln - 1].strip().lstrip("# ").strip())
            ln -= 1
        desc = " ".join(above + text)
        shown = json.dumps(value) if not isinstance(value, dict) else "see below"
        out += [f"| `{name}`", f"| `{esc(shown)}`", f"| {esc(desc)}", ""]
        if isinstance(value, dict):
            sub = ", ".join(f"`{a}`: `{json.dumps(b)}`" for a, b in value.items())
            out[-2] = f"| {esc(desc)} {sub}".rstrip()
    out += ["|===", ""]
    return write("settings.adoc", "\n".join(out)), len(keys)


# --------------------------------------------------------------------------------------- ribbons
def gen_ribbons():
    rdir = os.path.join(PKG, "resources", "ribbons")
    common = {t["name"]: t for t in json.load(open(os.path.join(rdir, "common.json"), encoding="utf-8"))["tabs"]}
    apps = json.load(open(os.path.join(rdir, "apps.json"), encoding="utf-8"))
    made = []

    def cmd_text(c):
        return " or ".join(f"`{x}`" for x in c) if isinstance(c, list) else f"`{c}`"

    def button(it, text):
        return text + (" _(when available)_" if it.get("optional") else "")

    def tab_rows(tab):
        rows = []
        for g in tab.get("groups") or []:
            for it in g.get("items", []):
                if "dropdown" in it:
                    for sub in it["items"]:
                        rows.append((g["name"], button(sub, f"{it['dropdown']} > {sub.get('label', sub['cmd'])}"),
                                     cmd_text(sub["cmd"])))
                else:
                    rows.append((g["name"], button(it, it.get("label", it["cmd"])), cmd_text(it["cmd"])))
        return rows

    for f in sorted(os.listdir(rdir)):
        if f in ("apps.json", "common.json") or not f.endswith(".json"):
            continue
        spec = json.load(open(os.path.join(rdir, f), encoding="utf-8"))
        name = os.path.splitext(f)[0]
        out = [f"// Generated by tools/gen_docs.py from resources/ribbons/{f}. Do not edit.", ""]
        for t in spec.get("tabs", []):
            if "include" in t:
                t = common.get(t["include"].split(":", 1)[1], {"name": t["include"], "groups": []})
            rows = tab_rows(t)
            if not rows:
                continue
            out += [f"=== {t['name']} tab", "", '[cols="2,3,4",options="header"]', "|===",
                    "| Group | NX button | FreeCAD command", ""]
            for g, label, cmd in rows:
                out += [f"| {esc(g)}", f"| {esc(label)}", f"| {cmd}", ""]
            out += ["|===", ""]
        made.append(write(f"ribbon-{name}.adoc", "\n".join(out)))
    # the applications list
    out = ["// Generated by tools/gen_docs.py from resources/ribbons/apps.json. Do not edit.", "",
           '[cols="2,3,2",options="header"]', "|===", "| Application | FreeCAD workbench | Key", ""]
    for g in apps["groups"]:
        for a in g["apps"]:
            out += [f"| {esc(a['title'])} ({esc(g['name'])})", f"| `{a['workbench']}`", f"| {kbd(a.get('shortcut', ''))}",
                    ""]
    out += ["|===", ""]
    made.append(write("applications.adoc", "\n".join(out)))
    return made


# ------------------------------------------------------------------------------------- tutorials
def gen_tutorials():
    if not os.path.isfile(RESULTS):
        print(f"no {RESULTS}: tutorial step tables skipped")
        return []
    data = json.load(open(RESULTS, encoding="utf-8"))
    steps = data["steps"]
    by = collections.OrderedDict()
    for s in steps:
        by.setdefault(s["tutorial"][:1], []).append(s)
    badge = {"same": "[.outcome.same]#same#", "differs": "[.outcome.differs]#differs#",
             "limit": "[.outcome.limit]#limit#", "missing": "[.outcome.missing]#missing#",
             "skipped": "[.outcome.skipped]#skipped#", "FAILED": "[.outcome.failed]#FAILED#"}
    made = []
    summary = ["// Generated by tools/gen_docs.py from docs/results/tutorials.json. Do not edit.", "",
               '[cols="4,1,1,1,1,1,1",options="header"]', "|===",
               "| Tutorial | same | differs | limit | missing | skipped | FAILED", ""]
    for key, rows in by.items():
        out = ["// Generated by tools/gen_docs.py from docs/results/tutorials.json. Do not edit.", "",
               '[cols="1,5,5,2,6",options="header",role="steps"]', "|===",
               "| # | In the book (NX) | In FreeCAD NX-Style | Result | Notes", ""]
        for r in rows:
            out += [f"| {key}{r['n']}", f"| {esc(r['nx'])}", f"| {esc(r['replay'])}",
                    f"| {badge.get(r['outcome'], esc(r['outcome']))}", f"| {esc(r['detail'])}", ""]
        out += ["|===", ""]
        made.append(write(f"tutorial-{key}.adoc", "\n".join(out)))
        c = collections.Counter(r["outcome"] for r in rows)
        title = rows[0]["tutorial"]
        summary += [f"| xref:tutorials/{key.lower()}.adoc[{esc(title)}]"] + \
                   [f"| {c.get(o, 0) or ''}" for o in ("same", "differs", "limit", "missing", "skipped", "FAILED")] + [""]
    summary += ["|===", ""]
    made.append(write("tutorial-summary.adoc", "\n".join(summary)))
    info = data.get("info", {})
    meta = f":replay-freecad: {'.'.join(info.get('FreeCAD', [])[:3]) or 'unknown'}\n:replay-steps: {len(steps)}\n"
    made.append(write("tutorial-meta.adoc", meta))
    return made


def import_results(path):
    """Copy a replay's tutorial.json into docs/results/: the steps and the FreeCAD version only."""
    data = json.load(open(path, encoding="utf-8"))
    steps = data["steps"]
    # a run of some tutorials (--tutorials O) replaces those tutorials only; the others stay as published
    if os.path.isfile(RESULTS):
        new = {s["tutorial"][:1] for s in steps}
        old = [s for s in json.load(open(RESULTS, encoding="utf-8"))["steps"] if s["tutorial"][:1] not in new]
        steps = sorted(old + steps, key=lambda s: (s["tutorial"][:1], s["n"]))
    keep = {"steps": steps, "info": {"FreeCAD": data.get("info", {}).get("FreeCAD", [])}}
    text = json.dumps(keep, indent=1, ensure_ascii=False)
    home = os.path.expanduser("~")
    if home in text or home.replace("\\", "/") in text or home.replace("\\", "\\\\") in text:
        print(f"refused: {path} names a folder under {home}; the results are published", file=sys.stderr)
        return False
    os.makedirs(os.path.dirname(RESULTS), exist_ok=True)
    with open(RESULTS + ".tmp", "w", encoding="utf-8", newline="\n") as f:
        f.write(text + "\n")
    os.replace(RESULTS + ".tmp", RESULTS)
    print(f"results: {len(keep['steps'])} steps from {path}")
    return True


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv[:1] == ["--results"] and len(argv) == 2:
        if not import_results(argv[1]):
            return 1
    elif argv:
        print(__doc__)
        return 2
    sc, n_sc = gen_shortcuts()
    st, n_st = gen_settings()
    rb = gen_ribbons()
    tu = gen_tutorials()
    print(f"shortcuts: {n_sc} keys; settings: {n_st}; ribbons: {len(rb)} files; tutorials: {len(tu)} files")
    print(f"written to {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
